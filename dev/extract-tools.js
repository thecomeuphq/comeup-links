// Extract the tool catalog from tools.html into a JS data module the new
// hub pages can use (problems hub, favorites, dashboard, catalog).
const fs = require('fs');

const html = fs.readFileSync('tools.html', 'utf8');

// Cards look like: <a class="card" href="X"><div class="t">Title</div><div class="d">Desc</div>
const re = /<a class="card([^"]*)" href="([^"]+)"[^>]*>\s*<div class="t">([\s\S]*?)<\/div>\s*<div class="d">([\s\S]*?)<\/div>/g;
const tools = [];
let m;
while ((m = re.exec(html))) {
  const cls = m[1] || '';
  const href = m[2];
  const title = m[3].replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').trim();
  const desc = m[4].replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').trim();
  if (href.startsWith('http')) continue; // gumroad / external
  tools.push({ href, title, desc, shop: /shop/.test(cls) });
}

console.log('EXTRACTED ' + tools.length + ' internal tools');
for (const t of tools) console.log('  ' + t.href + '  |  ' + t.title);

// Emit a JS module
const js = '// AUTO-GENERATED by dev/extract-tools.js — do not hand-edit.\n' +
  '// Source of truth: the card list in tools.html\n\n' +
  'const TOOLS = ' + JSON.stringify(tools, null, 2) + ';\n\n' +
  'module.exports = { TOOLS };\n';
fs.writeFileSync('gen/tool-data.js', js);
console.log('\nwrote gen/tool-data.js');
