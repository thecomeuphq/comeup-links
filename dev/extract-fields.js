// Extract (a) the shared .tcu share script and (b) each page's curated
// headline FIELDS, so new pages and the dashboard reuse real conventions.
const fs = require('fs');
const path = require('path');

function walk(dir, acc) {
  acc = acc || [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === '.git' || e.name === 'node_modules' || e.name === 'dev' || e.name === 'gen') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (e.name.endsWith('.html')) acc.push(p);
  }
  return acc;
}

const files = walk('.');

// ---- (a) the share script ----
const debtFree = fs.readFileSync('debt-free.html', 'utf8');
const sIdx = debtFree.indexOf('var SITE = "https://thecomeuphq.github.io/comeup-links";');
const eIdx = debtFree.indexOf('</script>', sIdx);
let shareScript = '';
if (sIdx > 0 && eIdx > 0) shareScript = debtFree.slice(sIdx, eIdx);
fs.writeFileSync('gen/share-script.txt', shareScript);
console.log('share script: ' + shareScript.length + ' bytes -> gen/share-script.txt');
console.log(shareScript.slice(0, 400));
console.log('...');
console.log(shareScript.slice(-700));

// ---- (b) curated FIELDS per page ----
const out = {};
for (const f of files) {
  const h = fs.readFileSync(f, 'utf8');
  const m = h.match(/var FIELDS\s*=\s*(\[[\s\S]*?\]);/);
  const p = h.match(/var PAGE_PATH\s*=\s*"([^"]+)"/);
  const intro = h.match(/var INTRO\s*=\s*"([^"]*)"/);
  if (m) {
    let fields = null;
    try { fields = JSON.parse(m[1]); } catch (e) { fields = null; }
    if (fields) {
      out[f.replace(/^\./, '').replace(/\\/g, '/')] = {
        fields,
        pagePath: p ? p[1] : null,
        intro: intro ? intro[1] : null
      };
    }
  }
}
fs.writeFileSync('gen/field-data.js',
  '// AUTO-GENERATED by dev/extract-fields.js — curated headline results per page.\n' +
  'const PAGE_FIELDS = ' + JSON.stringify(out, null, 2) + ';\n\nmodule.exports = { PAGE_FIELDS };\n');
console.log('\n\nPAGES WITH CURATED FIELDS: ' + Object.keys(out).length);
for (const [k, v] of Object.entries(out)) {
  console.log('  ' + k + '  ->  ' + v.fields.map(x => x.id + '(' + x.label + ')').join(', '));
}
